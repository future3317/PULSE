def _portfolio_split(sub: pd.DataFrame, n_splits: int, holdout_fold: int) -> tuple[pd.DataFrame, pd.DataFrame]:
    folds = sub["pair_id"].apply(lambda x: _hash_mod(x, n_splits))
    dev = sub[folds != holdout_fold].copy()
