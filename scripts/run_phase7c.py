    summaries["concordance_bands"] = pd.read_csv(RESULT_ROOT / "concordance_bands.csv")

    info_b = run_wp_b(enriched, cfg)
    summaries["high_response_sensitivity"] = pd.read_csv(RESULT_ROOT / "high_response_sensitivity.csv")

    info_c = run_wp_c(enriched, cfg)
    summaries["property_controls"] = pd.read_csv(RESULT_ROOT / "property_controls.csv")
    summaries["control_provenance"] = pd.read_csv(RESULT_ROOT / "control_provenance.csv")
    if (RESULT_ROOT / "property_control_curves.csv").exists():
        summaries["property_control_curves"] = pd.read_csv(RESULT_ROOT / "property_control_curves.csv")
    if (RESULT_ROOT / "property_control_comparison.csv").exists():
        summaries["property_control_comparison"] = pd.read_csv(RESULT_ROOT / "property_control_comparison.csv")

    info_d = run_wp_d(enriched, cfg)
    summaries["portfolio_benchmark"] = pd.read_csv(RESULT_ROOT / "portfolio_benchmark.csv")
