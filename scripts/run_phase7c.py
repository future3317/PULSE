def _result_hashes() -> list[dict[str, Any]]:
    hashes = []
    for path in sorted(RESULT_ROOT.glob("*.csv")):
        hashes.append({"path": str(path.relative_to(PROJECT_ROOT)), "sha256": _sha256_file(path)})
    for path in sorted(RESULT_ROOT.glob("*.json")):
        hashes.append({"path": str(path.relative_to(PROJECT_ROOT)), "sha256": _sha256_file(path)})
    return hashes


def _key_numbers(summaries: dict[str, pd.DataFrame], cfg: dict[str, Any] | None = None) -> dict[str, Any]:
    numbers: dict[str, Any] = {}
    ref_metric = "F1_Frobenius"
    if cfg is not None:
        ref_metric = cfg.get("property_controls", {}).get("reference_piezo_metric", "F1_Frobenius")
    conc = summaries.get("concordance_summary")
    if conc is not None and not conc.empty:
        row = conc[(conc["panel"] == "P0") & (conc["metric"] == ref_metric)]
        if not row.empty:
            numbers["P0_F1_nAUCC"] = float(row.iloc[0]["nAUCC"])
    bands = summaries.get("concordance_bands")
    if bands is not None and not bands.empty:
        for band in ["elite", "intermediate", "broad"]:
            row = bands[(bands["panel"] == "P0") & (bands["metric"] == ref_metric) & (bands["band"] == band)]
            if not row.empty:
                numbers[f"P0_F1_partial_nAUCC_{band}"] = float(row.iloc[0]["partial_nAUCC"])
    hr = summaries.get("high_response_sensitivity")
    if hr is not None and not hr.empty:
        dual = hr[
            (hr["panel"] == "P0")
            & (hr["metric"] == ref_metric)
            & (hr["method"] == "dual_high")
            & (hr["fraction"] == 0.10)
        ]
        if not dual.empty:
            numbers["P0_F1_dual_high_10pct_nAUCC"] = float(dual.iloc[0]["nAUCC"])
    prop = summaries.get("property_controls")
    if prop is not None and not prop.empty:
        ok = prop[(prop["status"] == "ok") & (prop["panel"] == "P0")]
        pos = ok[(ok["Delta_tau"].fillna(-np.inf) > 0) | (ok["Delta_nAUCC"].fillna(-np.inf) > 0)]
        numbers["n_positive_P0_controls"] = len(pos)
    port = summaries.get("portfolio_benchmark")
    if port is not None and not port.empty:
        primary = port[
            (port["eval_mode"] == "full_panel")
            & (port["is_primary"].eq(True))
            & (port["metric"] == ref_metric)
        ]
        if not primary.empty:
            best = primary.loc[primary["worst_source_recall"].idxmax()]
            numbers["primary_best_worst_source_recall"] = float(best["worst_source_recall"])
            numbers["primary_best_strategy"] = str(best["strategy"])
            numbers["primary_best_full_proc_delta_best_recall"] = float(
                best["full_proc_delta_best_recall"]
            )
            numbers["primary_best_full_proc_delta_best_recall_ci95_low"] = float(
                best["full_proc_delta_best_recall_ci95_low"]
            )
            numbers["primary_best_full_proc_delta_best_recall_ci95_high"] = float(
                best["full_proc_delta_best_recall_ci95_high"]
            )
    return numbers


def write_manifest(summaries: dict[str, pd.DataFrame], cfg: dict[str, Any]) -> dict[str, Any]:
    manifest = {
        "timestamp": _now(),
        "commit": _git_commit(),
        "config_commit": cfg["metadata"]["baseline_commit"],
        "branch": cfg["metadata"]["branch"],
        "files": _result_hashes(),
        "key_numbers": _key_numbers(summaries, cfg),
    }
    path = RESULT_ROOT / "phase7c_manifest.json"
    path.write_text(json.dumps(manifest, indent=2, default=str), encoding="utf-8")
    return {"manifest": {"path": str(path.relative_to(PROJECT_ROOT))}}


def main() -> int:
    parser = argparse.ArgumentParser(description="Run CrossPiezo Phase 7C")
    parser.add_argument("--dry-run", action="store_true", help="Print plan without writing files")
    args = parser.parse_args()

    cfg = _load_config()
    if args.dry_run:
        print("[dry-run] Phase 7C would run A-F work packages and write outputs to:")
        print(f"  artifacts: {ARTIFACT_ROOT}")
        print(f"  results:   {RESULT_ROOT}")
        print(f"  reports:   {REPORT_ROOT}")
        return 0

    ARTIFACT_ROOT.mkdir(parents=True, exist_ok=True)
    RESULT_ROOT.mkdir(parents=True, exist_ok=True)
    REPORT_ROOT.mkdir(parents=True, exist_ok=True)
    (ARTIFACT_ROOT / "figures").mkdir(parents=True, exist_ok=True)

    commit = _git_commit()
    print(f"[Phase 7C] commit={commit}")

    panel_df = load_panel()
    data_root = _resolve_data_root()
    jarvis, mp, _ = load_source_data(data_root)
    enriched = build_enriched_panel(panel_df, jarvis, mp)

    summaries: dict[str, pd.DataFrame] = {}

    info_a = run_wp_a(enriched, cfg)
    summaries["concordance_curve"] = pd.read_csv(RESULT_ROOT / "concordance_curve.csv")
