def _q_percentiles(cfg: dict[str, Any]) -> np.ndarray:
    sr = cfg["screening_resolution"]
    return np.arange(sr["q_percentiles"]["start"], sr["q_percentiles"]["stop"] + 1, sr["q_percentiles"]["step"])


def _panel_masks(enriched: pd.DataFrame, cfg: dict[str, Any]) -> dict[str, pd.Series]:
    masks: dict[str, pd.Series] = {}
    primary = cfg["panels"]["primary"]
    sensitivity = cfg["panels"]["sensitivity"]
    for base in (primary, sensitivity):
        masks[base] = enriched[base].astype(bool).copy()
        # High-response subset defined by pooled F1 response (reference metric).
        ref = cfg["property_controls"]["reference_piezo_metric"]
        metric = next(m for m in cfg["metrics"]["primary"] if m["name"] == ref)
        pooled = (enriched[metric["jarvis_col"]] + enriched[metric["mp_col"]]) / 2.0
        threshold = pooled.quantile(1.0 - cfg["panels"]["high_response_fraction"])
        masks[f"{base}{cfg['panels']['high_response_suffix']}"] = masks[base] & (pooled >= threshold)
    return masks


def run_wp_a(enriched: pd.DataFrame, cfg: dict[str, Any]) -> dict[str, Any]:
    print("[Phase 7B] Work Package A: screening-resolution curves...")
    q = _q_percentiles(cfg)
    sr = cfg["screening_resolution"]
    seed = sr["random_seed"]
    n_boot = sr["bootstrap_replicates"]
    alpha = 1.0 - sr["confidence_level"]
    delta_thresholds = sr["delta_thresholds"]
    metrics = cfg["metrics"]["primary"]
    panel_masks = _panel_masks(enriched, cfg)

    curve_rows: list[pd.DataFrame] = []
    summary_rows: list[dict[str, Any]] = []

    for panel_name, mask in panel_masks.items():
        sub = enriched[mask]
        for metric in metrics:
            left = sub[metric["jarvis_col"]].to_numpy()
            right = sub[metric["mp_col"]].to_numpy()
            curve = screening_resolution_curve(left, right, q, n_boot=n_boot, seed=seed, alpha=alpha)
            curve["panel"] = panel_name
            curve["metric"] = metric["name"]
            curve_rows.append(curve)

            summary: dict[str, Any] = {
                "panel": panel_name,
                "metric": metric["name"],
                "n_pairs": len(sub),
                "nAUCC": naucc(curve),
            }
            for delta in delta_thresholds:
                summary[f"q_consensus_delta{delta:.2f}"] = q_consensus_pointwise(curve, delta=delta)
                summary[f"persistent_onset_delta{delta:.2f}"] = persistent_onset(
                    curve, delta=delta, min_consecutive=sr["persistent_onset_min_consecutive"]
                )
            summary_rows.append(summary)

    curve_df = pd.concat(curve_rows, ignore_index=True)
    summary_df = pd.DataFrame(summary_rows)

    info = {
        "concordance_curve": _write_csv_with_hash(curve_df, RESULT_ROOT / "concordance_curve.csv"),
        "concordance_summary": _write_csv_with_hash(summary_df, RESULT_ROOT / "concordance_summary.csv"),
    }
    return info


