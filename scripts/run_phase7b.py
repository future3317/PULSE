def _subgroup_permutation_p(
    left: np.ndarray,
    right: np.ndarray,
    mask: np.ndarray,
    n_perm: int,
    seed: int,
) -> float:
    """Pair-level permutation p-value for tau_subgroup == tau_complement."""
    left = np.asarray(left, dtype=np.float64)
    right = np.asarray(right, dtype=np.float64)
    mask = np.asarray(mask, dtype=bool)
    n = len(left)
    tau_sub, _ = stats.kendalltau(left[mask], right[mask])
    tau_comp, _ = stats.kendalltau(left[~mask], right[~mask])
    if tau_sub is None or tau_comp is None:
        return float("nan")
    observed = float(tau_sub) - float(tau_comp)
    rng = np.random.default_rng(seed)
    b = 0
    for _ in range(n_perm):
        perm = rng.permutation(n)
        perm_mask = np.zeros(n, dtype=bool)
        perm_mask[perm[:mask.sum()]] = True
        t_sub, _ = stats.kendalltau(left[perm_mask], right[perm_mask])
        t_comp, _ = stats.kendalltau(left[~perm_mask], right[~perm_mask])
        if t_sub is None or t_comp is None:
            continue
        if abs(float(t_sub) - float(t_comp)) >= abs(observed):
            b += 1
    return (b + 1) / (n_perm + 1)


