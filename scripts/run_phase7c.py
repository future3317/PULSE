def run_wp_a(enriched: pd.DataFrame, cfg: dict[str, Any]) -> dict[str, Any]:
    print("[Phase 7C] Work Package A: screening-resolution curves and bands...")
    q = _q_percentiles(cfg)
    sr = cfg["screening_resolution"]
    seed = sr["random_seed"]
    n_boot = sr["bootstrap_replicates"]
    alpha = 1.0 - sr["confidence_level"]
    delta_thresholds = sr["delta_thresholds"]
    min_consecutive = sr["persistent_onset_min_consecutive"]
    metrics = cfg["metrics"]["primary"]
    bands = sr["bands"]
    panel_masks = _panel_masks(enriched, cfg)

    curve_rows: list[pd.DataFrame] = []
    summary_rows: list[dict[str, Any]] = []
    band_rows: list[dict[str, Any]] = []

    for panel_name, mask in panel_masks.items():
        sub = enriched[mask]
        for metric in metrics:
            left = sub[metric["jarvis_col"]].to_numpy(dtype=float)
            right = sub[metric["mp_col"]].to_numpy(dtype=float)
            curve = screening_resolution_curve(left, right, q, n_boot=n_boot, seed=seed, alpha=alpha)
            curve["panel"] = panel_name
            curve["metric"] = metric["name"]
            curve_rows.append(curve)

            summary: dict[str, Any] = {
                "panel": panel_name,
                "metric": metric["name"],
                "n_pairs": len(sub),
                "nAUCC": naucc(curve),
            }
            for delta in delta_thresholds:
                summary[f"q_consensus_delta{delta:.2f}"] = q_consensus_pointwise(curve, delta=delta)
                summary[f"persistent_onset_delta{delta:.2f}"] = persistent_onset(
                    curve, delta=delta, min_consecutive=min_consecutive
                )
            summary_rows.append(summary)

            for band in bands:
                band_rows.append(
                    {
                        "panel": panel_name,
                        "metric": metric["name"],
                        "band": band["name"],
                        "q_min": band["q_min"],
                        "q_max": band["q_max"],
                        "partial_nAUCC": partial_naucc(curve, band["q_min"], band["q_max"]),
                    }
                )

    curve_df = pd.concat(curve_rows, ignore_index=True)
    summary_df = pd.DataFrame(summary_rows)
    band_df = pd.DataFrame(band_rows)

    info = {
        "concordance_curve": _write_csv_with_hash(curve_df, RESULT_ROOT / "concordance_curve.csv"),
        "concordance_summary": _write_csv_with_hash(summary_df, RESULT_ROOT / "concordance_summary.csv"),
        "concordance_bands": _write_csv_with_hash(band_df, RESULT_ROOT / "concordance_bands.csv"),
    }
    return info


