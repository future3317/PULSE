def _high_response_subset_metrics(
    left: np.ndarray,
    right: np.ndarray,
    groups: np.ndarray,
    mask: np.ndarray,
    q: np.ndarray,
    n_boot: int,
    seed: int,
) -> dict[str, Any]:
    """Grouped bootstrap tau and nAUCC for a selected high-response subset."""
    if mask.sum() < 10:
        return {
            "n_selected": int(mask.sum()),
            "kendall_tau": float("nan"),
            "kendall_tau_ci95_low": float("nan"),
            "kendall_tau_ci95_high": float("nan"),
            "nAUCC": float("nan"),
            "nAUCC_ci95_low": float("nan"),
            "nAUCC_ci95_high": float("nan"),
        }
    tau, tau_lo, tau_hi = grouped_paired_bootstrap_tau(
        left[mask], right[mask], groups[mask], n_boot=n_boot, seed=seed
    )
    naucc_val, naucc_lo, naucc_hi = grouped_paired_bootstrap_naucc(
        left[mask], right[mask], q, groups[mask], n_boot=n_boot, seed=seed
    )
    return {
        "n_selected": int(mask.sum()),
        "kendall_tau": tau,
        "kendall_tau_ci95_low": tau_lo,
        "kendall_tau_ci95_high": tau_hi,
        "nAUCC": naucc_val,
        "nAUCC_ci95_low": naucc_lo,
        "nAUCC_ci95_high": naucc_hi,
    }


