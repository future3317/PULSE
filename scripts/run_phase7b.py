def run_wp_b(enriched: pd.DataFrame, cfg: dict[str, Any]) -> dict[str, Any]:
    print("[Phase 7B] Work Package B: scale/order/tail decomposition...")
    metrics = cfg["metrics"]["primary"]
    panel_masks = _panel_masks(enriched, cfg)
    tail_frac = cfg["scale_order_tail"]["tail_fraction"]
    grid = np.arange(
        cfg["scale_order_tail"]["quantile_mapping_grid"]["start"],
        cfg["scale_order_tail"]["quantile_mapping_grid"]["stop"]
        + cfg["scale_order_tail"]["quantile_mapping_grid"]["step"],
        cfg["scale_order_tail"]["quantile_mapping_grid"]["step"],
    )
    records: list[dict[str, Any]] = []

    for panel_name, mask in panel_masks.items():
        sub = enriched[mask]
        for metric in metrics:
            left = sub[metric["jarvis_col"]].to_numpy()
            right = sub[metric["mp_col"]].to_numpy()
            valid = np.isfinite(left) & np.isfinite(right) & (left > 0) & (right > 0)
            l_arr, r_arr = left[valid], right[valid]
            n = len(l_arr)
            if n < 10:
                continue

            ratio = r_arr / l_arr
            log_diff = np.log(r_arr) - np.log(l_arr)
            tau_raw, _ = stats.kendalltau(l_arr, r_arr)
            rho_raw, _ = stats.spearmanr(l_arr, r_arr)
            pl = stats.rankdata(l_arr, method="average") / n
            pr = stats.rankdata(r_arr, method="average") / n
            tau_q, _ = stats.kendalltau(pl, pr)
            rho_q, _ = stats.spearmanr(pl, pr)

            k_tail = max(1, int(tail_frac * n))
            top_l = set(np.argsort(-l_arr, kind="stable")[:k_tail].tolist())
            top_r = set(np.argsort(-r_arr, kind="stable")[:k_tail].tolist())
            crossings = len(top_l.symmetric_difference(top_r))

            ranks_l = stats.rankdata(-l_arr, method="average")
            ranks_r = stats.rankdata(-r_arr, method="average")
            abs_shift = np.abs(ranks_l - ranks_r)

            # ECDF comparison.
            ks_stat, ks_p = stats.ks_2samp(l_arr, r_arr)

            # Quantile mapping value error (residual after monotonic calibration).
            q_l = np.quantile(l_arr, grid)
            q_r = np.quantile(r_arr, grid)
            qm_mae = float(np.mean(np.abs(q_r - q_l)))

            # Threshold agreement at the tail fraction.
            in_l = np.zeros(n, dtype=bool)
            in_r = np.zeros(n, dtype=bool)
            in_l[list(top_l)] = True
            in_r[list(top_r)] = True
            kappa = cohen_kappa(in_l, in_r)

            records.append(
                {
                    "panel": panel_name,
                    "metric": metric["name"],
                    "n_pairs": n,
                    "jarvis_median": float(np.median(l_arr)),
                    "mp_median": float(np.median(r_arr)),
                    "median_ratio_mp_over_jarvis": float(np.median(ratio)),
                    "mean_log_ratio": float(np.mean(log_diff)),
                    "median_log_ratio": float(np.median(log_diff)),
                    "kendall_tau_raw": float(tau_raw) if tau_raw is not None else float("nan"),
                    "spearman_rho_raw": float(rho_raw) if rho_raw is not None else float("nan"),
                    "kendall_tau_quantile_normalized": float(tau_q) if tau_q is not None else float("nan"),
                    "spearman_rho_quantile_normalized": float(rho_q) if rho_q is not None else float("nan"),
                    "top_10pct_threshold_crossings": crossings,
                    "top_10pct_k": k_tail,
                    "ecdf_ks_stat": float(ks_stat),
                    "ecdf_ks_pvalue": float(ks_p),
                    "quantile_mapping_value_error_mae": qm_mae,
                    "threshold_agreement_kappa_at_top10": float(kappa),
                    "mean_rank_displacement": float(np.mean(abs_shift)),
                    "median_rank_displacement": float(np.median(abs_shift)),
                }
            )

    df = pd.DataFrame(records)
    info = {"scale_order_tail": _write_csv_with_hash(df, RESULT_ROOT / "scale_order_tail.csv")}
    return info


