def _grouped_bootstrap_delta_tau(
    left_a: np.ndarray,
    right_a: np.ndarray,
    left_b: np.ndarray,
    right_b: np.ndarray,
    groups: np.ndarray,
    n_boot: int,
    seed: int,
) -> tuple[float, float, float]:
    """Bootstrap CI for tau_a - tau_b using group resampling."""
    groups = np.asarray(groups)
    unique_groups = np.unique(groups)
    if len(unique_groups) < 2:
        return float("nan"), float("nan"), float("nan")
    idx_by_group = {g: np.where(groups == g)[0] for g in unique_groups}
    rng = np.random.default_rng(seed)
    reps: list[float] = []
    for _ in range(n_boot):
        sampled = rng.choice(unique_groups, size=len(unique_groups), replace=True)
        idx = np.concatenate([idx_by_group[g] for g in sampled])
        if len(idx) < 5:
            continue
        mask_a = np.isfinite(left_a[idx]) & np.isfinite(right_a[idx])
        mask_b = np.isfinite(left_b[idx]) & np.isfinite(right_b[idx])
        if mask_a.sum() < 5 or mask_b.sum() < 5:
            continue
        tau_a, _ = stats.kendalltau(left_a[idx][mask_a], right_a[idx][mask_a])
        tau_b, _ = stats.kendalltau(left_b[idx][mask_b], right_b[idx][mask_b])
        if tau_a is None or tau_b is None:
            continue
        reps.append(float(tau_a) - float(tau_b))
    if not reps:
        return float("nan"), float("nan"), float("nan")
    reps_arr = np.asarray(reps)
    point = float(np.mean(reps_arr))
    return point, float(np.percentile(reps_arr, 2.5)), float(np.percentile(reps_arr, 97.5))


