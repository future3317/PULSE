def _group_level_worst_recall(
    selected: list[int],
    left: np.ndarray,
    right: np.ndarray,
    q_star: float,
    groups: np.ndarray,
) -> tuple[np.ndarray, np.ndarray]:
    """Per-group worst-source recall for a global selection.

    Returns (group_labels, recalls).  The source elite set within each group
    uses the group size, so the metric is a grouped analogue of worst-source
    recall.
    """
    selected_set = set(selected)
    labels = np.unique(groups)
    recalls: list[float] = []
    for g in labels:
        idx = np.where(groups == g)[0]
        n_g = len(idx)
        if n_g == 0:
            recalls.append(float("nan"))
            continue
        k_g = max(1, int(math.floor(q_star * n_g)))
        top_j = set(np.argsort(-left[idx], kind="stable")[:k_g])
        top_m = set(np.argsort(-right[idx], kind="stable")[:k_g])
        sel_local = {i for i in range(n_g) if idx[i] in selected_set}
        r_j = len(sel_local & top_j) / k_g
        r_m = len(sel_local & top_m) / k_g
        recalls.append(float(min(r_j, r_m)))
    return labels, np.asarray(recalls, dtype=np.float64)


def _paired_diff_ci_vs_baseline(
    selected: list[int],
    baseline_selected: list[int],
    left: np.ndarray,
    right: np.ndarray,
    q_star: float,
    groups: np.ndarray,
    n_boot: int,
    seed: int,
) -> tuple[float, float, float]:
    """Paired difference (strategy - baseline) CI using group-level recalls."""
    labels_a, rec_a = _group_level_worst_recall(selected, left, right, q_star, groups)
    labels_b, rec_b = _group_level_worst_recall(baseline_selected, left, right, q_star, groups)
    # Labels are the same unique sorted set because both use the same groups.
    return paired_bootstrap_ci_difference(rec_a, rec_b, labels_a, n_boot=n_boot, seed=seed)


def _pareto_frontier(df: pd.DataFrame, recall_col: str, coverage_col: str) -> pd.DataFrame:
    """Flag non-dominated points (higher recall and higher coverage is better)."""
    df = df.copy()
    df["pareto_efficient"] = False
    points = df[[recall_col, coverage_col]].to_numpy(dtype=float)
    for i, (r, c) in enumerate(points):
        dominated = False
        for j, (rj, cj) in enumerate(points):
            if i == j:
                continue
            if rj >= r and cj >= c and (rj > r or cj > c):
                dominated = True
                break
        df.loc[df.index[i], "pareto_efficient"] = not dominated
    return df


