    hr = summaries.get("high_response_sensitivity")
    if hr is not None and not hr.empty:
        for _, row in hr.iterrows():
            key = f"{row['panel']}_{row['metric']}_frac{row['fraction']:.2f}_{row['method']}"
            numbers[key + "_n"] = int(row["n_selected"])
            numbers[key + "_nAUCC"] = float(row["nAUCC"]) if pd.notna(row["nAUCC"]) else None

    prop = summaries.get("property_controls")
    if prop is not None and not prop.empty:
        ok = prop[prop["status"] == "ok"]
        positive_controls = ok[
            (ok["Delta_tau"].fillna(-np.inf) > 0) | (ok["Delta_nAUCC"].fillna(-np.inf) > 0)
        ]
        numbers["n_positive_controls"] = len(positive_controls)
        numbers["control_attributes"] = positive_controls[["panel", "attribute", "Delta_tau", "Delta_nAUCC"]].to_dict(
            "records"
        )

    prov = summaries.get("control_provenance")
    if prov is not None and not prov.empty:
        numbers["control_same_field_copy_flags"] = prov[prov["same_field_copy_flag"]][["panel", "attribute"]].to_dict(
            "records"
        )

    port = summaries.get("portfolio_benchmark")
    if port is not None and not port.empty:
        ref_metric = cfg["property_controls"]["reference_piezo_metric"]
        primary = port[
            (port["eval_mode"] == "full_panel")
            & (port["is_primary"].eq(True))
            & (port["metric"] == ref_metric)
        ]
        if not primary.empty:
            best = primary.loc[primary["worst_source_recall"].idxmax()]
            numbers["primary_best_strategy"] = str(best["strategy"])
            numbers["primary_best_worst_source_recall"] = float(best["worst_source_recall"])
            numbers["primary_best_full_proc_delta_best_recall"] = float(
                best["full_proc_delta_best_recall"]
            )
            numbers["primary_best_full_proc_delta_best_recall_ci95_low"] = float(
                best["full_proc_delta_best_recall_ci95_low"]
            )
            numbers["primary_best_full_proc_delta_best_recall_ci95_high"] = float(
                best["full_proc_delta_best_recall_ci95_high"]
            )
            numbers["primary_best_metric"] = ref_metric

    numbers["baseline_commit"] = cfg["metadata"]["baseline_commit"]
    numbers["branch"] = cfg["metadata"]["branch"]
    numbers["timestamp"] = _now()

    info = _write_json_with_hash(numbers, RESULT_ROOT / "manuscript_numbers.json")
    return info


